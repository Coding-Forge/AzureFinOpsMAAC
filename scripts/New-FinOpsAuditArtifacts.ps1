        BillingPeriod = $AsOfDate.ToString("yyyy-MM")
        InvoiceId = ""
        BillingAccount = ""
        BillingProfile = ""
        Currency = $CommitmentCurrency
        InvoiceTotal = ""
        ExportActualCost = [math]::Round([decimal](($costRows | Measure-Object -Property ActualCost -Sum).Sum), 4)
        Variance = ""
        ReviewStatus = "Customer input required"
        Notes = "Enter invoice totals to reconcile exported Cost Management totals to billing records."
    }
)

