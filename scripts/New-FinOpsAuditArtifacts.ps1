    Group-Object AgreementId, Period, Currency |
    ForEach-Object {
        $groupRows = @($_.Group)
        $actual = ($groupRows | Measure-Object -Property ActualCost -Sum).Sum
        $matched = ($groupRows | Where-Object { $_.RetailMatchStatus -eq "Matched" } | Measure-Object -Property ActualCost -Sum).Sum
        $unmatched = $actual - $matched
        [pscustomobject][ordered]@{
            AgreementId = $AgreementId
