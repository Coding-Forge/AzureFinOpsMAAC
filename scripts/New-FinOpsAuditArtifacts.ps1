<#
.SYNOPSIS
Creates MACC agreement, benefit ledger, evidence, exception, and audit files for a FinOps export run.

.DESCRIPTION
This script reads the enriched Cost Management plus Retail Prices CSVs generated by Get-CostAnalysis.ps1
and creates customer-facing audit artifacts that can be loaded by the PBIP model.
#>
[CmdletBinding()]
param(
    [Parameter(Mandatory)]
    [string]$OutputRoot,

    [Parameter(Mandatory)]
    [string]$HistoryRoot,

    [string]$AnalysisMode = "Current",

    [string]$TenantId,

    [string[]]$SubscriptionIds = @(),

    [datetime]$AsOfDate = (Get-Date),

    [string]$StorageLocation = "Local",

    [string]$SettingsPath,

    [string]$AgreementId = "MACC-Agreement",

    [string]$CustomerName = "",

    [datetime]$AgreementStartDate = (Get-Date -Day 1),

    [datetime]$AgreementEndDate = (Get-Date -Day 1).AddYears(1).AddDays(-1),

    [decimal]$CommitmentAmount = 0,

    [string]$CommitmentCurrency = "USD",

    [decimal]$PacingWarningPercent = 10,

    [decimal]$PacingCriticalPercent = 20
)

$ErrorActionPreference = "Stop"

function ConvertTo-FinOpsDecimal {
    param([AllowNull()]$Value)

    if ($null -eq $Value -or [string]::IsNullOrWhiteSpace([string]$Value)) {
        return 0D
    }

    $parsed = 0D
    if ([decimal]::TryParse([string]$Value, [System.Globalization.NumberStyles]::Any, [System.Globalization.CultureInfo]::InvariantCulture, [ref]$parsed)) {
        return $parsed
    }

    return 0D
}

function Export-FinOpsCsv {
    param(
        [Parameter(Mandatory)]
        [string]$Path,

        [Parameter(Mandatory)]
        [string[]]$Columns,

        [object[]]$Rows = @()
    )

    New-Item -ItemType Directory -Path (Split-Path -Parent $Path) -Force | Out-Null
    $rowsToWrite = @($Rows | Where-Object { $null -ne $_ })

    if ($rowsToWrite.Count -eq 0) {
        $header = ($Columns | ForEach-Object { '"' + ($_ -replace '"', '""') + '"' }) -join ","
        Set-Content -Path $Path -Value $header -Encoding UTF8
        return
    }

    $rowsToWrite |
        Select-Object $Columns |
        Export-Csv -Path $Path -NoTypeInformation -Encoding UTF8
}

function Get-FinOpsCostRows {
    param([Parameter(Mandatory)][string]$RunRoot)

    $inputs = @(
        @{ Period = "MTD"; Path = Join-Path $RunRoot "mtd-cost-by-retail-join-enriched.csv" },
        @{ Period = "Last Month"; Path = Join-Path $RunRoot "last-month-cost-by-retail-join-enriched.csv" }
    )

    foreach ($input in $inputs) {
        if (-not (Test-Path $input.Path)) {
            Write-Warning "Audit artifacts could not find enriched cost file: $($input.Path)"
            continue
        }

        Import-Csv -Path $input.Path | ForEach-Object {
            $usageText = [string]$_.UsageDate
            $historyMonth = if ($usageText.Length -ge 6) { "$($usageText.Substring(0, 4))-$($usageText.Substring(4, 2))" } else { "" }
            $cost = ConvertTo-FinOpsDecimal $_.Cost
            $quantity = ConvertTo-FinOpsDecimal $_.UsageQuantity
            $retailPrice = ConvertTo-FinOpsDecimal $_.RetailPrice
            $retailEquivalent = if ($retailPrice -gt 0 -and $quantity -ne 0) { [math]::Round($quantity * $retailPrice, 6) } else { 0D }
            $estimatedSavings = $retailEquivalent - $cost

            $service = [string]$_.ServiceName
            $product = [string]$_.Product
            $eligibilityCategory = "Potentially eligible Azure consumption"
            $isEligible = "Yes"
            if ($cost -lt 0) {
                $eligibilityCategory = "Credit, refund, or adjustment"
                $isEligible = "No"
            }
            elseif ($service -match "Marketplace|Support" -or $product -match "Marketplace|Support") {
                $eligibilityCategory = "Marketplace or support review"
                $isEligible = "Review"
            }
            elseif ([string]::IsNullOrWhiteSpace($service) -or [string]::IsNullOrWhiteSpace($product)) {
                $eligibilityCategory = "Unknown - review source fields"
                $isEligible = "Review"
            }

            [pscustomobject][ordered]@{
                AgreementId = $AgreementId
                RunId = Split-Path -Leaf $RunRoot
                ExportedUtc = (Get-Date).ToUniversalTime().ToString("o")
                HistoryMonth = $historyMonth
                Period = $input.Period
                SubscriptionName = $_.SubscriptionName
                SubscriptionId = $_.SubscriptionId
                UsageDate = $_.UsageDate
                ServiceName = $_.ServiceName
                ResourceLocation = $_.ResourceLocation
                ArmRegionName = $_.ArmRegionName
                Meter = $_.Meter
                Product = $_.Product
                PartNumber = $_.PartNumber
                UnitOfMeasure = $_.UnitOfMeasure
                Currency = $_.Currency
                UsageQuantity = [double]$quantity
                ActualCost = [double]$cost
                EffectiveUnitCost = if ($quantity -ne 0) { [double]($cost / $quantity) } else { $null }
                RetailMatchStatus = $_.RetailMatchStatus
                RetailCandidateCount = $_.RetailCandidateCount
                RetailSkuId = $_.RetailSkuId
                RetailMeterId = $_.RetailMeterId
                RetailProductId = $_.RetailProductId
                RetailProductName = $_.RetailProductName
                RetailSkuName = $_.RetailSkuName
                RetailMeterName = $_.RetailMeterName
                RetailArmRegionName = $_.RetailArmRegionName
                RetailUnitOfMeasure = $_.RetailUnitOfMeasure
                RetailPrice = [double]$retailPrice
                RetailUnitPrice = [double](ConvertTo-FinOpsDecimal $_.RetailUnitPrice)
                RetailCurrencyCode = $_.RetailCurrencyCode
                RetailEquivalentCost = [double]$retailEquivalent
                EstimatedSavings = [double]$estimatedSavings
                IsMaccEligible = $isEligible
                MaccEligibilityCategory = $eligibilityCategory
            }
        }
    }
}

function New-FinOpsBenefitLedgerRows {
    param([object[]]$Rows)

    $Rows |
        Group-Object AgreementId, HistoryMonth, Period, SubscriptionId, SubscriptionName, ServiceName, ArmRegionName, Currency |
        ForEach-Object {
            $groupRows = @($_.Group)
            $first = $groupRows[0]
            $actualCost = ($groupRows | Measure-Object -Property ActualCost -Sum).Sum
            $retailEquivalent = ($groupRows | Measure-Object -Property RetailEquivalentCost -Sum).Sum
            $estimatedSavings = ($groupRows | Measure-Object -Property EstimatedSavings -Sum).Sum
            $matchedActual = ($groupRows | Where-Object { $_.RetailMatchStatus -eq "Matched" } | Measure-Object -Property ActualCost -Sum).Sum
            $eligible = ($groupRows | Where-Object { $_.IsMaccEligible -eq "Yes" } | Measure-Object -Property ActualCost -Sum).Sum
            $ineligible = ($groupRows | Where-Object { $_.IsMaccEligible -eq "No" } | Measure-Object -Property ActualCost -Sum).Sum
            $review = ($groupRows | Where-Object { $_.IsMaccEligible -eq "Review" } | Measure-Object -Property ActualCost -Sum).Sum

            [pscustomobject][ordered]@{
                AgreementId = $first.AgreementId
                HistoryMonth = $first.HistoryMonth
                Period = $first.Period
                ExportRunId = $first.RunId
                ExportedUtc = $first.ExportedUtc
                SubscriptionName = $first.SubscriptionName
                SubscriptionId = $first.SubscriptionId
                ServiceName = $first.ServiceName
                ArmRegionName = $first.ArmRegionName
                Currency = $first.Currency
                ActualCost = [math]::Round([decimal]$actualCost, 4)
                RetailEquivalentCost = [math]::Round([decimal]$retailEquivalent, 4)
                EstimatedSavings = [math]::Round([decimal]$estimatedSavings, 4)
                SavingsRate = if ($retailEquivalent -ne 0) { [math]::Round([decimal]($estimatedSavings / $retailEquivalent), 6) } else { 0 }
                MatchedActualCost = [math]::Round([decimal]$matchedActual, 4)
                UnmatchedActualCost = [math]::Round([decimal]($actualCost - $matchedActual), 4)
                RetailMatchCoverage = if ($actualCost -ne 0) { [math]::Round([decimal]($matchedActual / $actualCost), 6) } else { 0 }
                RowCount = $groupRows.Count
                MatchedRowCount = @($groupRows | Where-Object { $_.RetailMatchStatus -eq "Matched" }).Count
                ExceptionRowCount = @($groupRows | Where-Object { $_.RetailMatchStatus -ne "Matched" }).Count
                EligibleSpend = [math]::Round([decimal]$eligible, 4)
                IneligibleSpend = [math]::Round([decimal]$ineligible, 4)
                ReviewSpend = [math]::Round([decimal]$review, 4)
                CalculationVersion = "2026.06-audit-v1"
            }
        }
}

function Update-FinOpsBenefitLedger {
    param(
        [Parameter(Mandatory)][string]$LedgerPath,
        [Parameter(Mandatory)][object[]]$NewRows
    )

    $columns = @("AgreementId","HistoryMonth","Period","ExportRunId","ExportedUtc","SubscriptionName","SubscriptionId","ServiceName","ArmRegionName","Currency","ActualCost","RetailEquivalentCost","EstimatedSavings","SavingsRate","MatchedActualCost","UnmatchedActualCost","RetailMatchCoverage","RowCount","MatchedRowCount","ExceptionRowCount","EligibleSpend","IneligibleSpend","ReviewSpend","CalculationVersion")
    $existingRows = if (Test-Path $LedgerPath) { @(Import-Csv -Path $LedgerPath) } else { @() }
    $replaceKeys = @{}
    foreach ($row in $NewRows) {
        $replaceKeys["$($row.AgreementId)|$($row.HistoryMonth)|$($row.Period)|$($row.SubscriptionId)|$($row.ServiceName)|$($row.ArmRegionName)"] = $true
    }

    $keptRows = @(
        $existingRows | Where-Object {
            -not $replaceKeys.ContainsKey("$($_.AgreementId)|$($_.HistoryMonth)|$($_.Period)|$($_.SubscriptionId)|$($_.ServiceName)|$($_.ArmRegionName)")
        }
    )

    $allRows = @($keptRows) + @($NewRows)
    Export-FinOpsCsv -Path $LedgerPath -Columns $columns -Rows ($allRows | Sort-Object AgreementId, HistoryMonth, Period, SubscriptionName, ServiceName, ArmRegionName)
}

function New-FinOpsAgreementStatus {
    param([object[]]$LedgerRows)

    $eligibleToDate = ($LedgerRows | Measure-Object -Property EligibleSpend -Sum).Sum
    $remaining = [decimal]$CommitmentAmount - [decimal]$eligibleToDate
    $totalDays = [math]::Max(1, ($AgreementEndDate.Date - $AgreementStartDate.Date).Days + 1)
    $elapsedDays = [math]::Min($totalDays, [math]::Max(0, ($AsOfDate.Date - $AgreementStartDate.Date).Days + 1))
    $expectedBurn = if ($totalDays -gt 0) { [decimal]$CommitmentAmount * ([decimal]$elapsedDays / [decimal]$totalDays) } else { 0D }
    $burnVariance = [decimal]$eligibleToDate - $expectedBurn
    $pacingVariancePercent = if ($expectedBurn -ne 0) { $burnVariance / $expectedBurn } else { 0D }
    $runRateNeeded = if (($totalDays - $elapsedDays) -gt 0) { [decimal]$remaining / [decimal]($totalDays - $elapsedDays) * 30D } else { 0D }
    $status = "On track"
    if ($CommitmentAmount -le 0) {
        $status = "Commitment not configured"
    }
    elseif ($pacingVariancePercent -le -1D * ($PacingCriticalPercent / 100D)) {
        $status = "At risk"
    }
    elseif ($pacingVariancePercent -le -1D * ($PacingWarningPercent / 100D)) {
        $status = "Watch"
    }

    [pscustomobject][ordered]@{
        AgreementId = $AgreementId
        CustomerName = $CustomerName
        AgreementStartDate = $AgreementStartDate.ToString("yyyy-MM-dd")
        AgreementEndDate = $AgreementEndDate.ToString("yyyy-MM-dd")
        CommitmentAmount = [math]::Round([decimal]$CommitmentAmount, 4)
        CommitmentCurrency = $CommitmentCurrency
        AsOfDate = $AsOfDate.ToString("yyyy-MM-dd")
        EligibleSpendToDate = [math]::Round([decimal]$eligibleToDate, 4)
        RemainingCommitment = [math]::Round($remaining, 4)
        CommitmentUtilizationPercent = if ($CommitmentAmount -ne 0) { [math]::Round(([decimal]$eligibleToDate / [decimal]$CommitmentAmount), 6) } else { 0 }
        ExpectedBurnToDate = [math]::Round($expectedBurn, 4)
        BurnVariance = [math]::Round($burnVariance, 4)
        PacingVariancePercent = [math]::Round($pacingVariancePercent, 6)
        RequiredMonthlyRunRate = [math]::Round($runRateNeeded, 4)
        PacingStatus = $status
        PacingWarningPercent = [math]::Round([decimal]$PacingWarningPercent, 4)
        PacingCriticalPercent = [math]::Round([decimal]$PacingCriticalPercent, 4)
        CalculationVersion = "2026.06-audit-v1"
    }
}

New-Item -ItemType Directory -Path $OutputRoot -Force | Out-Null
New-Item -ItemType Directory -Path $HistoryRoot -Force | Out-Null

$runId = Split-Path -Leaf $OutputRoot
$exportedUtc = (Get-Date).ToUniversalTime().ToString("o")
$costRows = @(Get-FinOpsCostRows -RunRoot $OutputRoot)
$ledgerRowsForRun = @(New-FinOpsBenefitLedgerRows -Rows $costRows)
$ledgerPath = Join-Path $HistoryRoot "macc-benefit-ledger.csv"
