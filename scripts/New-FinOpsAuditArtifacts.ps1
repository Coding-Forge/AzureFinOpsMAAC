            ActualCost = $_.ActualCost
            RetailMatchStatus = $_.RetailMatchStatus
            RetailCandidateCount = $_.RetailCandidateCount
            IsMaccEligible = $_.IsMaccEligible
            MaccEligibilityCategory = $_.MaccEligibilityCategory
            ReviewStatus = "New"
            Owner = ""
            Resolution = ""
            Notes = ""
