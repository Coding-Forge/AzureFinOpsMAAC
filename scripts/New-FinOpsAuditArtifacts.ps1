$manifestRows = @(
    [pscustomobject][ordered]@{
        ExportRunId = $runId
        ExportedUtc = $exportedUtc
        AnalysisMode = $AnalysisMode
        StorageLocation = $StorageLocation
        TenantId = $TenantId
