        FileCount = @(Get-ChildItem -Path $OutputRoot -File -ErrorAction SilentlyContinue).Count
        ActualCost = [math]::Round([decimal](($costRows | Measure-Object -Property ActualCost -Sum).Sum), 4)
        RetailEquivalentCost = [math]::Round([decimal](($costRows | Measure-Object -Property RetailEquivalentCost -Sum).Sum), 4)
        EstimatedSavings = [math]::Round([decimal](($costRows | Measure-Object -Property EstimatedSavings -Sum).Sum), 4)
        CalculationVersion = "2026.06-audit-v1"
    }
)
