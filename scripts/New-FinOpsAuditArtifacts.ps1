            RetailMatchCoverage = if ($actual -ne 0) { [math]::Round([decimal]($matched / $actual), 6) } else { 0 }
            UnmatchedRowCount = @($groupRows | Where-Object { $_.RetailMatchStatus -ne "Matched" }).Count
            MultipleCandidateRowCount = @($groupRows | Where-Object { $_.RetailMatchStatus -eq "MultipleCandidates" }).Count
            ReviewEligibilityCost = [math]::Round([decimal](($groupRows | Where-Object { $_.IsMaccEligible -eq "Review" } | Measure-Object -Property ActualCost -Sum).Sum), 4)
            CalculationVersion = "2026.06-audit-v1"
        }
    }
