$agreementStatus = @(New-FinOpsAgreementStatus -LedgerRows $ledgerRowsAll)
Export-FinOpsCsv -Path (Join-Path $OutputRoot "macc-agreement-status.csv") -Columns @("AgreementId","CustomerName","AgreementStartDate","AgreementEndDate","CommitmentAmount","CommitmentCurrency","AsOfDate","EligibleSpendToDate","RemainingCommitment","CommitmentUtilizationPercent","ExpectedBurnToDate","BurnVariance","PacingVariancePercent","RequiredMonthlyRunRate","PacingStatus","PacingWarningPercent","PacingCriticalPercent","CalculationVersion") -Rows $agreementStatus

$auditColumns = @("AgreementId","RunId","ExportedUtc","HistoryMonth","Period","SubscriptionName","SubscriptionId","UsageDate","ServiceName","ResourceLocation","ArmRegionName","Meter","Product","PartNumber","UnitOfMeasure","Currency","UsageQuantity","ActualCost","EffectiveUnitCost","RetailMatchStatus","RetailCandidateCount","RetailSkuId","RetailMeterId","RetailProductId","RetailProductName","RetailSkuName","RetailMeterName","RetailArmRegionName","RetailUnitOfMeasure","RetailPrice","RetailUnitPrice","RetailCurrencyCode","RetailEquivalentCost","EstimatedSavings","IsMaccEligible","MaccEligibilityCategory")
Export-FinOpsCsv -Path (Join-Path $OutputRoot "agreement-price-audit.csv") -Columns $auditColumns -Rows $costRows

$priceSnapshotRows = $costRows |
    Where-Object { -not [string]::IsNullOrWhiteSpace([string]$_.RetailMeterId) } |
    Sort-Object RetailSkuId, RetailMeterId, RetailArmRegionName, RetailUnitOfMeasure -Unique |
    ForEach-Object {
        [pscustomobject][ordered]@{
            ExportRunId = $runId
            ExportedUtc = $exportedUtc
            RetailSkuId = $_.RetailSkuId
            RetailMeterId = $_.RetailMeterId
            RetailProductId = $_.RetailProductId
            RetailProductName = $_.RetailProductName
            RetailSkuName = $_.RetailSkuName
            RetailMeterName = $_.RetailMeterName
            RetailArmRegionName = $_.RetailArmRegionName
            RetailUnitOfMeasure = $_.RetailUnitOfMeasure
            RetailPrice = $_.RetailPrice
            RetailUnitPrice = $_.RetailUnitPrice
            RetailCurrencyCode = $_.RetailCurrencyCode
            Source = "Azure Retail Prices API selected match"
            CalculationVersion = "2026.06-audit-v1"
        }
    }
Export-FinOpsCsv -Path (Join-Path $OutputRoot "retail-price-snapshot.csv") -Columns @("ExportRunId","ExportedUtc","RetailSkuId","RetailMeterId","RetailProductId","RetailProductName","RetailSkuName","RetailMeterName","RetailArmRegionName","RetailUnitOfMeasure","RetailPrice","RetailUnitPrice","RetailCurrencyCode","Source","CalculationVersion") -Rows @($priceSnapshotRows)

$exceptionRows = $costRows |
    Where-Object { $_.RetailMatchStatus -ne "Matched" -or $_.IsMaccEligible -eq "Review" } |
    Sort-Object @{ Expression = "ActualCost"; Descending = $true } |
    ForEach-Object {
        [pscustomobject][ordered]@{
            ExceptionId = "$($_.RunId)|$($_.Period)|$($_.SubscriptionId)|$($_.ServiceName)|$($_.ArmRegionName)|$($_.Meter)"
            AgreementId = $_.AgreementId
