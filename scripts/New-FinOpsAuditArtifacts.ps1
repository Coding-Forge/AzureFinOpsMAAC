    [pscustomobject][ordered]@{
        AgreementId = $AgreementId
        CustomerName = $CustomerName
        AgreementStartDate = $AgreementStartDate.ToString("yyyy-MM-dd")
        AgreementEndDate = $AgreementEndDate.ToString("yyyy-MM-dd")
        CommitmentAmount = [math]::Round([decimal]$CommitmentAmount, 4)
        CommitmentCurrency = $CommitmentCurrency
        PacingWarningPercent = [math]::Round([decimal]$PacingWarningPercent, 4)
        PacingCriticalPercent = [math]::Round([decimal]$PacingCriticalPercent, 4)
        AsOfDate = $AsOfDate.ToString("yyyy-MM-dd")
        Notes = "Customer-maintained agreement metadata used for MACC burn-down and pacing."
    }
)
